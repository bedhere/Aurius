export function tAdmin(key: string, lang: 'en' | 'zh' = 'zh'): string {
  if (lang === 'zh') {
    const zh = ZH.admin[key];
    if (zh) return zh;
  }
  return key.replace(/([A-Z])/g, ' $1').replace(/^./, (c) => c.toUpperCase());
}
