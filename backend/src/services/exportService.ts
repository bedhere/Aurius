import * as XLSX from 'xlsx';
import PDFDocument from 'pdfkit';

// ---------------------------------------------------------------------------
// Excel / PDF export (requirements 64-65).
// Exports honour the exact filters passed in by the admin UI.
// ---------------------------------------------------------------------------

export interface ExportColumn {
  header: string;
  key: string;
}

export function buildExcelBuffer(sheetName: string, columns: ExportColumn[], rows: Record<string, unknown>[]): Buffer {
  const header = columns.map((c) => c.header);
  const data = rows.map((r) => columns.map((c) => (r[c.key] === null || r[c.key] === undefined ? '' : r[c.key])));
  const ws = XLSX.utils.aoa_to_sheet([header, ...data]);
  ws['!cols'] = columns.map((c) => ({ wch: Math.max(c.header.length + 4, 14) }));
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, sheetName);
  return XLSX.write(wb, { type: 'buffer', bookType: 'xlsx' }) as Buffer;
}

export function buildPdfBuffer(
  title: string,
  meta: { label: string; value: string }[],
  columns: ExportColumn[],
  rows: Record<string, unknown>[],
): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', layout: 'landscape', margin: 32 });
    const chunks: Buffer[] = [];
    doc.on('data', (c: Buffer) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    doc.fontSize(16).fillColor('#0DA19E').text(title, { align: 'left' });
    doc.moveDown(0.4);
    meta.forEach((m) => {
      doc.fontSize(9).fillColor('#44403c').text(`${m.label}: ${m.value}`);
    });
    doc.moveDown(0.6);

    // Table
    const colW = (doc.page.width - 64) / columns.length;
    const startY = doc.y;
    doc.fontSize(8).fillColor('#ffffff');
    doc.rect(32, startY, doc.page.width - 64, 18).fill('#0DA19E');
    let x = 32;
    columns.forEach((c) => {
      doc.fillColor('#ffffff').text(c.header, x + 4, startY + 5, { width: colW - 8 });
      x += colW;
    });
    let y = startY + 18;
    doc.fontSize(7.5);
    rows.slice(0, 400).forEach((row, idx) => {
      if (y > doc.page.height - 60) {
        doc.addPage();
        y = 32;
      }
      if (idx % 2 === 0) {
        doc.rect(32, y, doc.page.width - 64, 16).fill('#F5F5F4');
      }
      let cx = 32;
      columns.forEach((c) => {
        const v = row[c.key] === null || row[c.key] === undefined ? '' : String(row[c.key]);
        doc.fillColor('#1C1917').text(v, cx + 4, y + 4, { width: colW - 8, ellipsis: true });
        cx += colW;
      });
      y += 16;
    });

    doc
      .moveDown(1)
      .fontSize(8)
      .fillColor('#78716C')
      .text(`Generated by AURIUS Admin on ${new Date().toISOString()}`);
    doc.end();
  });
}
